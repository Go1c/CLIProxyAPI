func assertGeneratedCodexIdentityHeaders(t *testing.T, headers http.Header) string {
	t.Helper()

	sessionID := headerValueCaseInsensitive(headers, "session_id")
	if sessionID == "" {
		t.Fatalf("session_id is empty; headers=%#v", headers)
	}
	if got := headers.Get("X-Client-Request-Id"); got != sessionID {
		t.Fatalf("X-Client-Request-Id = %s, want session_id %s", got, sessionID)
	}
	if got := headers.Get("X-Codex-Window-Id"); got != sessionID+":0" {
		t.Fatalf("X-Codex-Window-Id = %s, want %s:0", got, sessionID)
	}

	metaRaw := headers.Get("X-Codex-Turn-Metadata")
	if metaRaw == "" {
		t.Fatalf("X-Codex-Turn-Metadata is empty")
	}
	if got := gjson.Get(metaRaw, "session_id").String(); got != sessionID {
		t.Fatalf("metadata session_id = %s, want %s; raw=%s", got, sessionID, metaRaw)
	}
	if got := gjson.Get(metaRaw, "thread_source").String(); got != "user" {
		t.Fatalf("metadata thread_source = %s, want user; raw=%s", got, metaRaw)
	}
	if got := gjson.Get(metaRaw, "sandbox").String(); got != "seccomp" {
		t.Fatalf("metadata sandbox = %s, want seccomp; raw=%s", got, metaRaw)
	}
	if got := gjson.Get(metaRaw, "turn_id").String(); got == "" {
		t.Fatalf("metadata turn_id is empty; raw=%s", metaRaw)
	}
	if got := gjson.Get(metaRaw, "turn_started_at_unix_ms").Int(); got <= 0 {
		t.Fatalf("metadata turn_started_at_unix_ms = %d, want positive; raw=%s", got, metaRaw)
	}
	return sessionID
}

func contextWithGinHeaders(headers map[string]string) context.Context {
	gin.SetMode(gin.TestMode)
	recorder := httptest.NewRecorder()
	ginCtx, _ := gin.CreateTestContext(recorder)
	ginCtx.Request = httptest.NewRequest(http.MethodPost, "/", nil)
	ginCtx.Request.Header = make(http.Header, len(headers))
	for key, value := range headers {
		ginCtx.Request.Header.Set(key, value)
	}
	return context.WithValue(context.Background(), "gin", ginCtx)
}

